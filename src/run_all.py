"""Load data/clean into SQLite, run every query in sql/, and check the answers.

  python src/run_all.py            check against answers/expected.json (exit 1 on any difference)
  python src/run_all.py --update   rewrite answers/expected.json from the current data
Also writes answers/results.md, a readable copy of every result.
"""
import csv, json, os, sqlite3, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES = ["patients", "spells", "episodes", "diagnoses", "procedures", "ref_icd10", "ref_opcs4", "ref_treatment_function",
          "ref_admission_method", "ref_discharge_destination", "ref_discharge_method", "population", "ref_esp2013"]


def load():
    db = sqlite3.connect(":memory:")
    db.executescript(open(os.path.join(ROOT, "sql", "schema.sql")).read())
    for t in TABLES:
        with open(os.path.join(ROOT, "data", "clean", f"{t}.csv"), newline="") as f:
            rows = list(csv.reader(f))
        cols = rows[0]
        db.executemany(f"INSERT INTO {t} ({','.join(cols)}) VALUES ({','.join('?' * len(cols))})",
                       [[None if v == "" else v for v in r] for r in rows[1:]])
    return db


def main():
    db = load()
    index = json.load(open(os.path.join(ROOT, "sql", "index.json")))
    exp_path = os.path.join(ROOT, "answers", "expected.json")
    expected = {} if "--update" in sys.argv or not os.path.exists(exp_path) else json.load(open(exp_path))
    out, results, fails = ["# Results\n", "Generated by `src/run_all.py` (SQLite).\n"], {}, 0
    for q in index:
        t = time.time()
        cur = db.execute(open(os.path.join(ROOT, "sql", q["file"])).read())
        cols = [c[0] for c in cur.description]
        rows = [list(r) for r in cur.fetchall()]
        results[q["id"]] = {"columns": cols, "rows": rows}
        ok = q["id"] not in expected or expected[q["id"]] == results[q["id"]]
        fails += not ok
        print(f"{'PASS' if ok else 'FAIL'} {q['id']} {len(rows)} rows {time.time() - t:.1f}s")
        out += [f"\n## {q['id'].upper()} · {q['title']}\n", q["question"] + "\n",
                "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        out += ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in rows]
    os.makedirs(os.path.join(ROOT, "answers"), exist_ok=True)
    open(os.path.join(ROOT, "answers", "results.md"), "w").write("\n".join(out) + "\n")
    if "--update" in sys.argv:
        json.dump(results, open(exp_path, "w"), indent=1)
        print("expected answers written")
    raise SystemExit(1 if fails else 0)


if __name__ == "__main__":
    main()
